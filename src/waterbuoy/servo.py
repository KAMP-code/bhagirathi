"""Hobby servo control (e.g. TowerPro SG90) on a Raspberry Pi GPIO pin.

A hobby servo is positioned by a pulse repeated at 50 Hz: the pulse width (about
0.5-2.4 ms on an SG90) sets the angle. Pulses are generated by lgpio's `tx_servo`,
which times them in a background C thread, so no hardware-PWM overlay is needed and
any GPIO pin works.

    from waterbuoy.servo import Servo

    with Servo(16) as s:          # GPIO16 (BCM numbering), physical pin 36
        s.angle = 90              # jump to 90 degrees
        s.move_to(0, speed=60)    # sweep to 0 degrees at 60 deg/s
        s.detach()                # stop pulses: servo goes limp, no hum/jitter

Wiring (SG90): brown = GND, red = +5 V, orange = signal -> GPIO16. Power the servo
from 5 V, not 3.3 V, and share ground with the Pi. A stalled SG90 can draw ~700 mA, so
use an external 5 V supply if the Pi resets or the servo stutters.

Requires the system package python3-lgpio (`sudo apt install python3-lgpio`) and the
user in the `gpio` group.
"""

from __future__ import annotations

import logging
import threading
import time
from typing import Protocol

log = logging.getLogger(__name__)


class PulseDriver(Protocol):
    """Low-level output: emits `pulse_us`-wide pulses at `frequency` Hz until stopped."""

    def set_pulse(self, pulse_us: int, frequency: int) -> None: ...
    def stop(self) -> None: ...
    def close(self) -> None: ...


def find_gpiochip() -> int:
    """Number of the gpiochip driving the 40-pin header (Pi 5: RP1, earlier Pis: BCM)."""
    import lgpio

    for chip in range(16):
        try:
            h = lgpio.gpiochip_open(chip)
        except lgpio.error:
            continue
        try:
            label = lgpio.gpio_get_chip_info(h)[3]
        finally:
            lgpio.gpiochip_close(h)
        if label.startswith("pinctrl-"):  # pinctrl-rp1, pinctrl-bcm2711, pinctrl-bcm2835
            return chip
    raise RuntimeError("no Raspberry Pi header gpiochip found (expected a 'pinctrl-*' gpiochip)")


class LgpioDriver:
    """Pulse output through lgpio (software-timed by lgpio's C thread)."""

    def __init__(self, pin: int, chip: int | None = None):
        try:
            import lgpio
        except ImportError as e:
            raise RuntimeError("lgpio not installed; run: sudo apt install python3-lgpio") from e
        self._lgpio = lgpio
        self.pin = pin
        self.chip = find_gpiochip() if chip is None else chip
        try:
            self.handle = lgpio.gpiochip_open(self.chip)
        except lgpio.error as e:
            raise RuntimeError(f"cannot open /dev/gpiochip{self.chip}: {e} (is the user in group 'gpio'?)") from e
        try:
            lgpio.gpio_claim_output(self.handle, pin, 0)
        except lgpio.error as e:
            lgpio.gpiochip_close(self.handle)
            raise RuntimeError(f"cannot use GPIO{pin}: {e} (in use by another program?)") from e
        self._pulsing = False

    def set_pulse(self, pulse_us: int, frequency: int) -> None:
        self._lgpio.tx_servo(self.handle, self.pin, int(pulse_us), frequency)
        self._pulsing = True

    def read(self) -> int:
        """Current level of the pin (used by tests to measure the signal)."""
        return self._lgpio.gpio_read(self.handle, self.pin)

    def stop(self) -> None:
        if self._pulsing:  # lgpio rejects "stop" when no pulse train is running
            self._lgpio.tx_servo(self.handle, self.pin, 0)
            self._pulsing = False
        self._lgpio.gpio_write(self.handle, self.pin, 0)

    def close(self) -> None:
        try:
            self.stop()
            self._lgpio.gpio_free(self.handle, self.pin)
        finally:
            self._lgpio.gpiochip_close(self.handle)


class Servo:
    """Angle control of a hobby servo.

    Angles from `min_angle` to `max_angle` map linearly onto pulse widths from
    `min_pulse_us` to `max_pulse_us`. The defaults suit an SG90 (0-180 degrees over
    500-2400 us). If the servo buzzes or strains at an end stop, narrow the pulse range.
    """

    def __init__(
        self,
        pin: int = 16,
        *,
        min_pulse_us: int = 500,
        max_pulse_us: int = 2400,
        min_angle: float = 0.0,
        max_angle: float = 180.0,
        frequency: int = 50,
        driver: PulseDriver | None = None,
    ):
        if not 0 < min_pulse_us < max_pulse_us < 1_000_000 / frequency:
            raise ValueError("need 0 < min_pulse_us < max_pulse_us < pulse period")
        if not min_angle < max_angle:
            raise ValueError("need min_angle < max_angle")
        self.pin = pin
        self.min_pulse_us = min_pulse_us
        self.max_pulse_us = max_pulse_us
        self.min_angle = float(min_angle)
        self.max_angle = float(max_angle)
        self.frequency = frequency
        self.driver: PulseDriver = driver if driver is not None else LgpioDriver(pin)
        self._lock = threading.Lock()
        self._angle: float | None = None   # None = detached (no pulses)
        self._closed = False

    # --- conversions -----------------------------------------------------
    def pulse_for(self, angle: float) -> int:
        self._check(angle)
        frac = (angle - self.min_angle) / (self.max_angle - self.min_angle)
        return round(self.min_pulse_us + frac * (self.max_pulse_us - self.min_pulse_us))

    def _check(self, angle: float) -> None:
        if not self.min_angle <= angle <= self.max_angle:
            raise ValueError(f"angle {angle} outside {self.min_angle:g}..{self.max_angle:g}")

    # --- control ---------------------------------------------------------
    @property
    def angle(self) -> float | None:
        """Last commanded angle, or None when detached. (An SG90 has no position
        feedback, so this is the target, not a measurement.)"""
        return self._angle

    @angle.setter
    def angle(self, value: float) -> None:
        self.set_angle(value)

    @property
    def attached(self) -> bool:
        return self._angle is not None

    def set_angle(self, angle: float) -> None:
        """Command `angle` immediately (the servo moves at full speed)."""
        pulse = self.pulse_for(angle)
        with self._lock:
            self._ensure_open()
            self.driver.set_pulse(pulse, self.frequency)
            self._angle = float(angle)
        log.debug("servo GPIO%d -> %.1f deg (%d us)", self.pin, angle, pulse)

    def move_to(self, angle: float, speed: float | None = None, step: float = 1.0) -> None:
        """Move to `angle`. With `speed` (deg/s) the move is a smooth, blocking sweep in
        `step`-degree increments, starting from the current angle; without it, or when
        detached (start position unknown), it jumps there."""
        self._check(angle)
        start = self._angle
        if speed is None or start is None:
            self.set_angle(angle)
            return
        if speed <= 0 or step <= 0:
            raise ValueError("speed and step must be > 0")
        steps = max(1, round(abs(angle - start) / step))
        dt = abs(angle - start) / speed / steps
        t_next = time.monotonic()
        for i in range(1, steps + 1):
            self.set_angle(start + (angle - start) * i / steps)
            t_next += dt
            time.sleep(max(0.0, t_next - time.monotonic()))

    def center(self) -> None:
        self.set_angle((self.min_angle + self.max_angle) / 2)

    def detach(self) -> None:
        """Stop sending pulses. The SG90 stops holding its position (no hum, no power
        draw from holding torque) and stays roughly where it was."""
        with self._lock:
            if self._closed:
                return
            self.driver.stop()
            self._angle = None

    def close(self) -> None:
        """Stop pulses and release the GPIO pin. Safe to call twice."""
        with self._lock:
            if self._closed:
                return
            self._closed = True
            self._angle = None
            self.driver.close()

    def _ensure_open(self) -> None:
        if self._closed:
            raise RuntimeError("servo is closed")

    def __enter__(self) -> Servo:
        return self

    def __exit__(self, *exc) -> None:
        self.close()

    def __repr__(self) -> str:
        return f"Servo(pin={self.pin}, angle={self._angle})"
